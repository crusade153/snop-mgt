/**
 * LV2 → 채널. 표에 없으면 `미분류`.
 *
 * ⚠️ **`기타` 로 떨어뜨리지 않는다.** `기타` 는 사업부가 지정한 실제 채널(부자재·반제품·계열사)이라
 * 매핑 누락과 섞이면 "이 7.8억이 진짜 기타인지 매핑이 빠진 건지" 구분할 수 없게 된다.
 * 미분류는 화면에 금액으로 드러내고, 표에 줄을 더하면 재적재 없이 과거 주차까지 함께 옮겨간다.
 *
 * 앞뒤 공백만 떼고 그 밖의 정규화는 하지 않는다(위 파일 주석의 공백 두 칸 항목 참고).
 */
export function channelOfLv2(lv2?: string | null): WeeklyChannel {
  const key = String(lv2 ?? '').trim();
  if (!key) return '미분류';
  return CHANNEL_BY_LV2[key] || '미분류';
}

/** 표 행 정렬 가중치. `WEEKLY_CHANNEL_ORDER` 순서를 그대로 쓴다 */
export function channelSortWeight(channel: WeeklyChannel) {
  const index = WEEKLY_CHANNEL_ORDER.indexOf(channel);
  return index < 0 ? WEEKLY_CHANNEL_ORDER.length : index;
}
